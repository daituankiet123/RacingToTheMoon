export const WEATHER_CYCLE_ORDER: WeatherType[] = ['clear', 'sunset', 'rain', 'fog', 'snow'];

export function resolveWeatherForState(
  cityDefault: WeatherType,
  setting: WeatherSetting,
  elapsedSec: number
): WeatherType {
  if (setting === 'city') return cityDefault;
  if (setting === 'dynamic') {
    const startIdx = Math.max(0, WEATHER_CYCLE_ORDER.indexOf(cityDefault));
    const phaseIdx = Math.floor(Math.max(0, elapsedSec) / 28) % WEATHER_CYCLE_ORDER.length;
    return WEATHER_CYCLE_ORDER[(startIdx + phaseIdx) % WEATHER_CYCLE_ORDER.length];
  }
  return setting;
}

